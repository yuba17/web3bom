"""Report generators for audit findings.

Supports multiple output formats:
  - Internal markdown report (default)
  - Code4rena competition submission format
  - Immunefi bug bounty submission format
  - Cantina competition submission format
"""
import json
import os
from datetime import datetime
from pathlib import Path

TEMPLATES_DIR = Path(__file__).parent / "templates"

# ---------------------------------------------------------------------------
# Severity mapping: internal severity -> platform severity
# ---------------------------------------------------------------------------
SEVERITY_MAP_C4 = {
    "CRITICAL": "High",   # C4 has no "Critical"; highest is High (3)
    "HIGH": "High",
    "MEDIUM": "Medium",
    "LOW": "QA",
    "INFO": "QA",
}

SEVERITY_MAP_IMMUNEFI = {
    "CRITICAL": "Critical",
    "HIGH": "High",
    "MEDIUM": "Medium",
    "LOW": "Low",
    "INFO": "Insight",     # Immunefi doesn't pay for these
}

SEVERITY_MAP_CANTINA = {
    "CRITICAL": "Critical",
    "HIGH": "High",
    "MEDIUM": "Medium",
    "LOW": "Low",
    "INFO": "Informational",
}


def _map_severity(severity: str, platform: str) -> str:
    """Map internal severity to platform-specific severity."""
    maps = {
        "code4rena": SEVERITY_MAP_C4,
        "immunefi": SEVERITY_MAP_IMMUNEFI,
        "cantina": SEVERITY_MAP_CANTINA,
    }
    sev_map = maps.get(platform, {})
    return sev_map.get(severity, severity)


# ---------------------------------------------------------------------------
# Internal markdown report (original format)
# ---------------------------------------------------------------------------
def generate_markdown_report(findings: list[dict], target: str) -> str:
    """Generate the internal markdown audit report (unchanged from v1)."""
    severity_counts = {}
    for f in findings:
        sev = f.get("severity", "INFO")
        severity_counts[sev] = severity_counts.get(sev, 0) + 1

    lines = [
        f"# Smart Contract Audit Report",
        f"",
        f"**Target:** `{target}`",
        f"**Date:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        f"**Tool:** Web3 Audit Agents",
        f"",
        f"## Summary",
        f"",
        f"| Severity | Count |",
        f"|----------|-------|",
    ]

    for sev in ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]:
        count = severity_counts.get(sev, 0)
        if count > 0:
            lines.append(f"| {sev} | {count} |")

    lines.append(f"| **Total** | **{len(findings)}** |")
    lines.append("")

    # Group by severity
    for sev in ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]:
        sev_findings = [f for f in findings if f.get("severity") == sev]
        if not sev_findings:
            continue

        lines.append(f"## {sev} Findings")
        lines.append("")

        for i, f in enumerate(sev_findings, 1):
            lines.append(f"### {sev}-{i:02d}: {f.get('title', 'Untitled')}")
            lines.append("")
            lines.append(f"**Agent:** {f.get('agent', 'Unknown')}")
            if f.get("location"):
                lines.append(f"**Location:** `{f['location']}`")
            lines.append("")
            lines.append(f"**Description:** {f.get('description', '')}")
            lines.append("")
            if f.get("code_snippet"):
                lines.append(f"```solidity")
                lines.append(f"{f['code_snippet']}")
                lines.append(f"```")
                lines.append("")
            if f.get("recommendation"):
                lines.append(f"**Recommendation:** {f['recommendation']}")
                lines.append("")
            lines.append("---")
            lines.append("")

    lines.append("*Generated by Web3 Audit Agents*")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Code4rena format
# ---------------------------------------------------------------------------
def generate_code4rena_report(finding: dict, repo_url: str = "") -> str:
    """Generate a single Code4rena High/Medium submission.

    Code4rena requires INDIVIDUAL submissions for High/Medium findings.
    Low/QA findings should be batched via generate_code4rena_qa_report().

    Args:
        finding: Dict with keys: title, severity, location, description,
                 code_snippet, recommendation, impact, poc, root_cause
        repo_url: GitHub repo URL for the audit (e.g.,
                  "https://github.com/code-423n4/2026-XX-protocol")
    """
    sev = _map_severity(finding.get("severity", "MEDIUM"), "code4rena")
    title = finding.get("title", "Untitled Finding")
    location = finding.get("location", "")
    description = finding.get("description", "")
    impact = finding.get("impact", description)
    code_snippet = finding.get("code_snippet", "")
    recommendation = finding.get("recommendation", "")
    poc = finding.get("poc", "")
    root_cause = finding.get("root_cause", "")

    # Build GitHub permalink
    permalink = ""
    if repo_url and location:
        # Convert "src/Contract.sol:123" -> GitHub URL
        parts = location.split(":")
        file_path = parts[0].replace("\\", "/")
        line = parts[1] if len(parts) > 1 else ""
        permalink = f"{repo_url}/blob/main/{file_path}"
        if line:
            permalink += f"#L{line}"

    lines = []

    # Lines of code
    lines.append("## Lines of code\n")
    if permalink:
        lines.append(permalink)
    else:
        lines.append(f"`{location}`")
    lines.append("")

    # Vulnerability details
    lines.append("## Vulnerability details\n")
    lines.append(f"### Impact\n")
    lines.append(impact)
    lines.append("")

    # Proof of Concept
    lines.append("### Proof of Concept\n")
    if poc:
        lines.append("```solidity")
        lines.append(poc)
        lines.append("```")
    else:
        lines.append("<!-- TODO: Add runnable Foundry PoC -->")
        if code_snippet:
            lines.append("\n**Vulnerable code:**\n")
            lines.append("```solidity")
            lines.append(code_snippet)
            lines.append("```")
    lines.append("")

    # Tools Used
    lines.append("### Tools Used\n")
    lines.append("Manual review, Foundry\n")

    # Recommended mitigation
    lines.append("### Recommended Mitigation Steps\n")
    if root_cause:
        lines.append(f"**Root Cause:** {root_cause}\n")
    lines.append(recommendation)
    lines.append("")

    return "\n".join(lines)


def generate_code4rena_qa_report(findings: list[dict], repo_url: str = "") -> str:
    """Generate a consolidated Code4rena QA report for Low/Info findings.

    Code4rena requires ALL Low and Centralization/Governance findings
    in a single QA report per warden.
    """
    low_findings = [f for f in findings
                    if f.get("severity") in ("LOW", "INFO")]

    lines = ["# QA Report\n"]

    for i, f in enumerate(low_findings, 1):
        sev_prefix = "L" if f.get("severity") == "LOW" else "NC"
        title = f.get("title", "Untitled")
        location = f.get("location", "")
        description = f.get("description", "")
        recommendation = f.get("recommendation", "")

        lines.append(f"## [{sev_prefix}-{i:02d}] {title}\n")
        if location:
            lines.append(f"**Location:** `{location}`\n")
        lines.append(f"{description}\n")
        if recommendation:
            lines.append(f"**Recommendation:** {recommendation}\n")
        lines.append("")

    return "\n".join(lines)


